// Principal decision flow: registration manager sends → metivta principal decides → manager sees it.
import { createClient } from "@supabase/supabase-js";
const URL = process.env.SB_URL, KEY = process.env.SB_KEY, PW = process.env.E2E_PW;
const login = async (r) => { const c = createClient(URL, KEY, { auth: { persistSession: false } }); const { error } = await c.auth.signInWithPassword({ email: `e2e-${r}@test.local`, password: PW }); if (error) throw error; return c; };
let fails = 0; const ok = (n, c, x = "") => { if (!c) fails++; console.log(`${c ? "PASS" : "FAIL"} ${n} ${x}`); };
const adm = await login("admin"), mgr = await login("manager"), prin = await login("principal"), sec = await login("secretary");
const { data: fx } = await adm.rpc("insert_students", { p_rows: [
  { firstName: "E2E", lastName: "מנהל-מתיבתא", grade: 8, registrationTrack: "metivta" },
  { firstName: "E2E", lastName: "מנהל-מאור", grade: 8, registrationTrack: "maor_israel" }] });
const [met, maor] = fx;
const s1 = await sec.from("principal_reviews").insert({ student_id: met.id, request_note: "x" });
ok("secretary cannot send (no principal.request)", !!s1.error);
const r1 = await mgr.from("principal_reviews").insert({ student_id: met.id, request_note: "נפגשו ביום ראשון" }).select().single();
ok("manager sends to principal", !r1.error, r1.error?.message);
ok("requester name stamped", r1.data?.requested_by_name === "בדיקה manager", r1.data?.requested_by_name);
const r2 = await mgr.from("principal_reviews").insert({ student_id: met.id });
ok("no duplicate pending request", r2.error?.code === "23505");
await mgr.from("principal_reviews").insert({ student_id: maor.id });
const seen = ((await prin.from("principal_reviews").select("student_id").eq("status", "pending")).data ?? []).map((r) => r.student_id);
ok("principal sees metivta request", seen.includes(met.id));
ok("principal does NOT see other institution", !seen.includes(maor.id));
const st = await prin.from("students").select("id, first_name").eq("id", met.id).single();
ok("principal can open the student", st.data?.id === met.id);
const m1 = await mgr.from("principal_reviews").update({ status: "decided", decision: "accept" }).eq("id", r1.data.id).select();
ok("manager cannot decide", !!m1.error || (m1.data ?? []).length === 0);
const p0 = await prin.from("principal_reviews").update({ status: "decided" }).eq("id", r1.data.id).select();
ok("decision requires accept/reject", !!p0.error || (p0.data ?? []).length === 0);
const p1 = await prin.from("principal_reviews").update({ status: "decided", decision: "accept", summary: "בחור מצוין, מתקבל" }).eq("id", r1.data.id).select().single();
ok("principal decides", !p1.error && p1.data?.decided_by_name === "בדיקה principal", p1.error?.message);
const back = (await mgr.from("principal_reviews").select("*").eq("id", r1.data.id).single()).data;
ok("manager sees decision + summary", back?.decision === "accept" && back?.summary === "בחור מצוין, מתקבל" && !back?.seen_at);
const p2 = await prin.from("students").update({ first_name: "hack" }).eq("id", met.id).select();
ok("principal cannot edit the student", !!p2.error || (p2.data ?? []).length === 0);
const sn = await mgr.from("principal_reviews").update({ seen_at: new Date().toISOString() }).eq("id", r1.data.id).select().single();
ok("manager marks as read", !!sn.data?.seen_at, sn.error?.message);
const o = await mgr.rpc("patch_student", { p_id: met.id, p_patch: { details: { outcome: "accepted" } } });
ok("manager applies outcome to card", !o.error, o.error?.message);
const p3 = await prin.from("principal_reviews").update({ decision: "reject", summary: "שיניתי דעתי" }).eq("id", r1.data.id).select().single();
ok("principal can revise; resets read flag", p3.data?.decision === "reject" && !p3.data?.seen_at, p3.error?.message);
const again = await mgr.from("principal_reviews").insert({ student_id: met.id }).select().single();
ok("can send again after decision", !again.error, again.error?.message);
const c = await mgr.from("principal_reviews").update({ status: "cancelled" }).eq("id", again.data.id).select().single();
ok("manager cancels", c.data?.status === "cancelled", c.error?.message);
const v = await login("viewer");
ok("viewer sees nothing", ((await v.from("principal_reviews").select("id")).data ?? []).length === 0);
await adm.from("students").delete().in("id", [met.id, maor.id]);
console.log(fails ? `${fails} FAILED` : "ALL PASSED");
process.exit(fails ? 1 : 0);
