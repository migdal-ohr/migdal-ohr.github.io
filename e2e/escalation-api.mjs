import { createClient } from "@supabase/supabase-js";
const URL = process.env.SB_URL, KEY = process.env.SB_KEY, PW = process.env.E2E_PW;
const login = async (r) => { const c = createClient(URL, KEY, { auth: { persistSession: false } }); await c.auth.signInWithPassword({ email: `e2e-${r}@test.local`, password: PW }); return c; };
let fails = 0; const ok = (n, c) => { if (!c) fails++; console.log(`${c ? "PASS" : "FAIL"} ${n}`); };
const adm = await login("admin");
const { data: role } = await adm.from("roles").insert({ name: "E2E מנהל משתמשים", perms: { "students.view": true, "admin.users": true } }).select().single();
const { data: vp } = await adm.from("profiles").select("user_id").eq("email", "e2e-viewer@test.local").single();
await adm.from("profiles").update({ role_id: role.id }).eq("user_id", vp.user_id);
const v = await login("viewer");
const adminRole = (await v.from("roles").select("id").eq("key", "admin").single()).data.id;
const a = await v.from("profiles").update({ role_id: adminRole }).eq("user_id", vp.user_id).select();
ok("user-manager cannot make self system admin", !!a.error || (a.data ?? []).length === 0);
const { data: ap } = await adm.from("profiles").select("user_id").eq("email", "e2e-admin@test.local").single();
const b = await v.from("profiles").update({ is_active: false }).eq("user_id", ap.user_id).select();
ok("user-manager cannot disable a system admin", !!b.error || (b.data ?? []).length === 0);
const c = await v.from("roles").update({ is_admin: true }).eq("id", role.id).select().single();
ok("cannot turn a custom role into super-admin", !c.data || c.data.is_admin === false);
const d = await v.functions.invoke("admin-users", { body: { action: "set_password", user_id: ap.user_id, password: "Hacked-12345" } });
ok("cannot reset a system admin's password", !!d.error);
const sec = (await v.from("roles").select("id").eq("key", "secretary").single()).data.id;
const { data: sp } = await adm.from("profiles").select("user_id").eq("email", "e2e-secretary@test.local").single();
const e = await v.from("profiles").update({ role_id: sec }).eq("user_id", sp.user_id).select();
ok("user-manager CAN manage regular users", !e.error && (e.data ?? []).length === 1);
await adm.from("profiles").update({ role_id: (await adm.from("roles").select("id").eq("key", "viewer").single()).data.id }).eq("user_id", vp.user_id);
await adm.from("roles").delete().eq("id", role.id);
console.log(fails ? `${fails} FAILED` : "ALL ESCALATION CHECKS PASSED");
