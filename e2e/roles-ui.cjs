const { chromium } = require('playwright'); const path = require('path');
const S = path.join(__dirname, 'shots'); const BASE = 'http://127.0.0.1:4173';
(async () => {
  const b = await chromium.launch({ proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined });
  const errs = [];
  const login = async (r) => { const ctx = await b.newContext({ viewport: { width: 1400, height: 1000 }, locale: 'he-IL' }); const p = await ctx.newPage(); p.on('pageerror', e => errs.push(r + ': ' + e.message));
    await p.goto(BASE + '/auth'); await p.getByLabel('אימייל').fill(`e2e-${r}@test.local`); await p.getByLabel('סיסמה').fill(process.env.E2E_PW);
    await p.getByRole('button', { name: 'כניסה' }).click(); await p.getByRole('heading', { name: 'המשימות להיום' }).waitFor({ timeout: 30000 }); return p; };
  const p = await login('admin');
  await p.getByRole('button', { name: /ניהול מערכת/ }).click();
  await p.getByRole('tab', { name: /תפקידים והרשאות/ }).click();
  await p.getByRole('button', { name: 'תפקיד חדש', exact: true }).click();
  await p.waitForFunction(() => document.querySelector('#role-name')?.value?.startsWith('תפקיד חדש'));
  await p.waitForTimeout(1500);
  await p.getByLabel('שם התפקיד').fill('E2E מזכירת מתיבתא');
  await p.getByRole('button', { name: 'מתיבתא', exact: true }).click();
  await p.getByLabel('מחיקה סופית').waitFor();
  await p.getByRole('button', { name: /שמירת התפקיד/ }).click();
  await p.getByText(/התפקיד עודכן/).waitFor({ timeout: 10000 });
  console.log('PASS admin created & saved a custom role in the UI');
  await p.screenshot({ path: S + '/roles-01.png', fullPage: true });
  await p.getByRole('tab', { name: /^משתמשים/ }).click();
  await p.getByText('e2e-viewer@test.local').waitFor();
  const row = p.locator('div.flex', { has: p.getByText('e2e-viewer@test.local') }).last();
  await row.getByRole('combobox', { name: 'תפקיד' }).click();
  await p.getByRole('option', { name: 'E2E מזכירת מתיבתא' }).click();
  await p.getByText('עודכן').first().waitFor();
  console.log('PASS assigned the role to a user');
  const v = await login('viewer');
  const sidebar = await v.locator('aside').first().innerText();
  console.log(/E2E מזכירת מתיבתא/.test(sidebar) ? 'PASS user sees new role name' : 'FAIL role name');
  console.log(/ניהול מערכת/.test(sidebar) ? 'FAIL viewer sees admin' : 'PASS no admin menu for custom role');
  console.log('ERRORS', errs.length ? errs : 'none'); await b.close();
})().catch(e => { console.log('FATAL', e.message); process.exit(1); });
