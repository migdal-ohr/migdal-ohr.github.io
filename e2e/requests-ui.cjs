const { chromium } = require('playwright'); const path = require('path');
const S = path.join(__dirname, 'shots'); const BASE = 'http://127.0.0.1:4173';
(async () => {
  const b = await chromium.launch({ proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined });
  const errs = [];
  const login = async (r) => { const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, locale: 'he-IL' }); const p = await ctx.newPage(); p.on('pageerror', e => errs.push(r + ': ' + e.message));
    await p.goto(BASE + '/auth'); await p.getByLabel('אימייל').fill(`e2e-${r}@test.local`); await p.getByLabel('סיסמה').fill(process.env.E2E_PW);
    await p.getByRole('button', { name: 'כניסה' }).click(); await p.getByRole('heading', { name: 'המשימות להיום' }).waitFor({ timeout: 30000 }); return p; };
  const mgr = await login('manager');
  const sec = await login('secretary');
  await sec.getByRole('button', { name: /בקשות ותקלות/ }).click();
  await sec.getByText('פנייה חדשה').waitFor();
  await sec.getByRole('button', { name: /רעיון/ }).click();
  await sec.getByLabel('נושא').fill('E2E להוסיף שדה קופת חולים');
  await sec.getByLabel('פירוט (לא חובה)').fill('בכרטיס התלמיד, כמו במערכת הישנה');
  await sec.getByText('הפנייה תגיע למנהלת הרישום').waitFor();
  console.log('PASS secretary sees it goes to the registration manager');
  await sec.getByRole('button', { name: 'שליחה' }).click();
  await sec.getByText('E2E להוסיף שדה קופת חולים').first().waitFor({ timeout: 15000 });
  console.log('PASS request appears in secretary list');
  await sec.screenshot({ path: S + '/req-01-secretary.png' });
  await mgr.getByText(/פנייה חדשה: E2E/).first().waitFor({ timeout: 15000 });
  console.log('PASS manager got a live popup');
  const badge = await mgr.getByRole('button', { name: /בקשות ותקלות/ }).innerText();
  console.log(/1/.test(badge) ? 'PASS manager sidebar badge shows 1' : 'FAIL badge: ' + badge);
  await mgr.getByRole('button', { name: /בקשות ותקלות/ }).click();
  await mgr.getByRole('tab', { name: /לטיפולי/ }).click();
  await mgr.getByPlaceholder('תשובה למי שפנה (תופיע אצלו)').fill('מעבירה לאריאל להוספה');
  await mgr.getByRole('button', { name: /העבר למנהל המערכת/ }).click();
  await mgr.getByText('אצל מנהל המערכת').first().waitFor({ timeout: 10000 });
  console.log('PASS manager escalated to admin');
  await mgr.screenshot({ path: S + '/req-02-manager.png' });
  console.log('ERRORS', errs.length ? errs : 'none'); await b.close();
})().catch(e => { console.log('FATAL', e.message); process.exit(1); });
