const { chromium } = require('playwright'); const path = require('path');
const S = path.join(__dirname, 'shots'); const BASE = 'http://127.0.0.1:4173';
(async () => {
  const b = await chromium.launch({ proxy: process.env.HTTPS_PROXY ? { server: process.env.HTTPS_PROXY, bypass: '127.0.0.1,localhost' } : undefined });
  const errs = [];
  const ctx = await b.newContext({ viewport: { width: 1400, height: 1000 }, locale: 'he-IL' }); const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message));
  await p.goto(BASE + '/auth'); await p.getByLabel('אימייל').fill('e2e-secretary@test.local'); await p.getByLabel('סיסמה').fill(process.env.E2E_PW);
  await p.getByRole('button', { name: 'כניסה' }).click(); await p.getByRole('heading', { name: 'המשימות להיום' }).waitFor({ timeout: 30000 });
  await p.getByRole('button', { name: /הוסף תלמיד חדש/ }).click();
  const dlg = p.getByRole('dialog');
  await dlg.getByPlaceholder('לדוגמה: משה').fill('בדיקה');
  await dlg.getByPlaceholder('לדוגמה: כהן').fill('כרטיס');
  await dlg.locator('button[role=combobox]').filter({ hasText: 'בחר/י מסלול' }).click();
  await p.getByRole('option', { name: 'מתיבתא' }).click();
  await dlg.getByPlaceholder('רחוב ומספר').fill('הרב בוסקילה 5');
  await dlg.locator('label:has-text("קופת חולים") + button, div:has(> label:text("קופת חולים")) button[role=combobox]').first().click();
  await p.getByRole('option', { name: 'מכבי' }).click();
  await p.screenshot({ path: S + '/card-01-step1.png' });
  await dlg.getByRole('button', { name: 'המשך לשלב הבא' }).click();
  await dlg.getByPlaceholder('לדוגמה: אבי').fill('אבא');
  await dlg.locator('input[placeholder="05X-XXXXXXX"]:visible').first().fill('052-0000002');
  await dlg.getByRole('button', { name: /כתובת התלמיד לשני ההורים/ }).click();
  await dlg.getByLabel('אמא מקבל/ת וואטסאפ').click();
  await p.screenshot({ path: S + '/card-02-step2.png' });
  await dlg.getByRole('button', { name: 'המשך לשלב הבא' }).click();
  await dlg.locator('div:has(> label:text("קייטנה")) button[role=combobox]').first().click();
  await p.getByRole('option', { name: 'מגיע', exact: true }).click();
  await p.screenshot({ path: S + '/card-03-step3.png' });
  await dlg.getByRole('button', { name: 'הוספת תלמיד' }).click();
  await p.getByText('תלמיד/ה חדש/ה נוסף/ה').first().waitFor({ timeout: 15000 });
  console.log('PASS created student through the 3-step form');
  console.log('ERRORS', errs.length ? errs : 'none'); await b.close();
})().catch(e => { console.log('FATAL', e.message.slice(0, 400)); process.exit(1); });
